import { expect, it, vi } from "vitest";
import fs from "node:fs/promises";
import path from "node:path";
import { buildServer } from "../../src/server.js";
import { closeMetaDb } from "../../src/lib/meta-sqlite.js";
import { SetupTokenStore } from "../../src/lib/setup-token-store.js";
import { loadConfig } from "../../src/lib/config.js";

it("persists administrator plugin choice for the next Server startup", async () => {
  const parent = path.resolve(__dirname, "../../../../tmp/plugin-settings");
  await fs.mkdir(parent, { recursive: true });
  const root = await fs.mkdtemp(path.join(parent, "settings-"));
  const env = { DATA_DIR: root, LISTEN_PORT: "0", BOOTSTRAP_API_KEY: "plugin-settings-admin-key", JWT_SECRET: "test-secret" };
  const tokens = new SetupTokenStore();
  const requestRestart = vi.fn();
  let app = await buildServer({ env, setupTokens: tokens, restartController: { requestRestart } });
  try {
    const token = tokens.issue();
    expect((await app.inject({ method: "POST", url: "/api/setup/initialize", payload: { token: token.token, username: "owner", password: "correct-horse-battery" } })).statusCode).toBe(201);
    const url = "/api/system/settings/plugins";
    expect((await app.inject({ url })).statusCode).toBe(401);
    const headers = { "X-API-Key": env.BOOTSTRAP_API_KEY };
    expect((await app.inject({ url, headers })).json().data.combination).toBe("full");
    expect((await app.inject({ method: "PUT", url, headers, payload: { combination: "invalid" } })).statusCode).toBe(400);
    expect((await app.inject({ method: "PUT", url, headers, payload: { combination: "full", documentsEnabled: "false" } })).statusCode).toBe(400);
    expect((await app.inject({ method: "PUT", url, headers, payload: { combination: "multiuser", documentsEnabled: false } })).statusCode).toBe(202);
    expect(requestRestart).toHaveBeenCalledWith(75);
    expect((await loadConfig(env)).pluginCombination).toBe("multiuser");
    expect((await loadConfig(env)).documentsEnabled).toBe(false);
    expect((await app.inject({ url: "/api/system/plugins" })).json().data.combination).toBe("full");
    await app.close(); closeMetaDb();
    app = await buildServer({ env, restartController: { requestRestart } });
    expect((await app.inject({ url: "/api/system/plugins" })).json().data.combination).toBe("multiuser");
    expect((await app.inject({ url, headers })).json().data.documentsEnabled).toBe(false);
    const settings = await app.inject({ url: "/api/agent/app-settings?appId=platform", headers });
    expect(settings.statusCode, settings.body).toBe(200);
    expect(settings.json().data.skills).toHaveLength(4);
    expect(settings.json().data.skills.every((skill: { available: boolean }) => !skill.available)).toBe(true);
    expect((await app.inject({ url: "/api/development/creations" })).statusCode).toBe(404);
    expect((await app.inject({ method: "PUT", url, headers, payload: { combination: "multiuser", documentsEnabled: true } })).statusCode).toBe(202);
    await app.close(); closeMetaDb();
    app = await buildServer({ env, restartController: { requestRestart } });
    expect((await app.inject({ url, headers })).json().data.documentsEnabled).toBe(true);
    const restored = await app.inject({ url: "/api/agent/app-settings?appId=platform", headers });
    expect(restored.statusCode, restored.body).toBe(200);
    expect(restored.json().data.skills).toHaveLength(4);
    expect(restored.json().data.skills.every((skill: { unavailableReason?: string }) => skill.unavailableReason !== "公共文档扩展尚未启用。")).toBe(true);
    await app.close(); closeMetaDb();
    app = await buildServer({ env: { ...env, LOCALAPP_PLUGIN_COMBINATION: "platform" }, restartController: { requestRestart } });
    expect((await app.inject({ url, headers })).json().data).toEqual({ combination: "platform", controlledByEnvironment: true, documentsEnabled: true, documentsControlled: false });
    const before = requestRestart.mock.calls.length;
    expect((await app.inject({ method: "PUT", url, headers, payload: { combination: "full" } })).statusCode).toBe(409);
    expect(requestRestart.mock.calls.length).toBe(before);
    expect((await loadConfig(env)).pluginCombination).toBe("multiuser");
    expect((await app.inject({ method: "PUT", url, headers, payload: { combination: "platform", documentsEnabled: false } })).statusCode).toBe(202);
    expect((await loadConfig(env)).pluginCombination).toBe("multiuser");
    expect((await loadConfig(env)).documentsEnabled).toBe(false);
    await app.close(); closeMetaDb();
    app = await buildServer({ env, documents: false, restartController: { requestRestart } });
    expect((await app.inject({ url, headers })).json().data.documentsControlled).toBe(true);
    expect((await app.inject({ method: "PUT", url, headers, payload: { combination: "multiuser", documentsEnabled: true } })).statusCode).toBe(409);
    expect((await app.inject({ method: "PUT", url, headers, payload: { combination: "full", documentsEnabled: false } })).statusCode).toBe(202);
    expect((await loadConfig(env)).pluginCombination).toBe("full");
    expect((await loadConfig(env)).documentsEnabled).toBe(false);
  } finally { await app.close(); closeMetaDb(); await fs.rm(root, { recursive: true, force: true }); }
});
