import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const defaultRootDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function assertObject(value, name) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${name} must be an object`);
  }
}

function validateCapabilities(value) {
  assertObject(value, "capabilities");
  if (value.$schema !== "./capabilities.schema.json") throw new Error("capabilities.$schema is invalid");
  if (value.schemaVersion !== 1) throw new Error("capabilities.schemaVersion must be 1");
  if (!/^\d+\.\d+\.\d+$/.test(value.platformVersion)) throw new Error("capabilities.platformVersion must be semver");
  for (const key of ["content", "backend", "identity", "collaboration", "verification"]) {
    assertObject(value[key], `capabilities.${key}`);
  }
  if (!Number.isInteger(value.content.upload?.maxBytes) || value.content.upload.maxBytes <= 0) {
    throw new Error("capabilities.content.upload.maxBytes must be a positive integer");
  }
  if (!Array.isArray(value.content.types) || value.content.types.length === 0) {
    throw new Error("capabilities.content.types must not be empty");
  }
  if (value.backend.stableMode !== "named-sql" || value.backend.namedSql?.enabled !== true) {
    throw new Error("capabilities.backend must declare named-sql as the stable mode");
  }
  if (value.backend.hostedActions?.enabled !== false) {
    throw new Error("capabilities.backend.hostedActions must remain disabled while unstable");
  }
  if (value.collaboration.recordVersioned?.enabled !== true || value.collaboration.crdt?.enabled !== true) {
    throw new Error("capabilities.collaboration must enable record-versioned and crdt");
  }
  if (value.collaboration.crdt.protocol !== "yjs-v1"
    || !Number.isInteger(value.collaboration.crdt.maxDocumentBytes)
    || value.collaboration.crdt.maxDocumentBytes < 1024
    || value.collaboration.crdt.awareness !== true
    || value.collaboration.crdt.editingOverlay !== true) {
    throw new Error("capabilities.collaboration.crdt is invalid");
  }
  if (!Array.isArray(value.verification.identities)) {
    throw new Error("capabilities.verification.identities must be an array");
  }
  for (const key of ["defaultTtlSeconds", "maxTtlSeconds", "maxConcurrentSessions", "maxDatabaseBytes"]) {
    if (!Number.isInteger(value.verification[key]) || value.verification[key] <= 0) {
      throw new Error(`capabilities.verification.${key} must be a positive integer`);
    }
  }
}

function generatedTypeScript(capabilities, sourceHash) {
  return `// Generated by scripts/generate-platform-capabilities.mjs. Do not edit.\n\nexport const PLATFORM_CAPABILITIES = ${JSON.stringify(capabilities, null, 2)} as const;\n\nexport type PlatformCapabilities = typeof PLATFORM_CAPABILITIES;\n\nexport const PLATFORM_CAPABILITIES_SOURCE_SHA256 = ${JSON.stringify(sourceHash)};\n`;
}

async function writeOrCheck(filePath, expected, check) {
  if (check) {
    const actual = await readFile(filePath, "utf8").catch(() => null);
    if (actual !== expected) throw new Error(`${filePath} is not synchronized with platform/capabilities.json`);
    return;
  }
  await mkdir(dirname(filePath), { recursive: true });
  await writeFile(filePath, expected, "utf8");
}

export async function generatePlatformCapabilities({ rootDir = defaultRootDir, check = false } = {}) {
  const sourcePath = resolve(rootDir, "platform/capabilities.json");
  const sourceBytes = await readFile(sourcePath);
  const capabilities = JSON.parse(sourceBytes.toString("utf8"));
  validateCapabilities(capabilities);

  const sourceHash = createHash("sha256").update(sourceBytes).digest("hex");
  const normalizedJson = `${JSON.stringify(capabilities, null, 2)}\n`;
  await writeOrCheck(
    resolve(rootDir, "packages/dsh-app-platform/src/platform-capabilities.cts"),
    generatedTypeScript(capabilities, sourceHash),
    check,
  );
  await writeOrCheck(
    resolve(rootDir, "init-repo/runtime/platform-capabilities.json"),
    normalizedJson,
    check,
  );

  return { capabilities, sourceHash };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  generatePlatformCapabilities({ check })
    .then(() => console.log(check ? "Platform capabilities are synchronized." : "Generated platform capabilities."))
    .catch((error) => {
      console.error(error.message);
      process.exitCode = 1;
    });
}
